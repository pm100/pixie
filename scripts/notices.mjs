// Builds the third-party notices: every licence text of the software that ships in Pixie, and who uses it.
//   - Rust crates: from `cargo about` (settings in about.toml, which stops on a licence we have not accepted).
//   - npm packages the UI ships: from ui/node_modules.
//   - Everything else (libheif, libde265, ONNX Runtime, the downloaded models, map data): docs/notices/extra.json.
// Writes ui/src/generated/third-party.json (what Settings, About shows) and THIRD-PARTY-NOTICES.md (the same, as text).
// Run it with `just notices` and commit the result.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (...p) => readFileSync(join(root, ...p), 'utf8');
const norm = (s) => s.replace(/\r\n/g, '\n').trim();

/** licence text -> { license, text, packages: [{ name, version, url, note }] } */
const groups = new Map();
function add(license, text, pkg) {
  const key = norm(text);
  if (!groups.has(key)) groups.set(key, { license, text: key, packages: [] });
  const g = groups.get(key);
  if (!g.packages.some((p) => p.name === pkg.name && p.version === pkg.version)) g.packages.push(pkg);
}

// Rust crates.
const out = join(tmpdir(), 'pixie-about.json');
execFileSync('cargo', ['about', 'generate', '--format', 'json', '-o', out], { cwd: root, stdio: ['ignore', 'ignore', 'inherit'] });
const about = JSON.parse(readFileSync(out, 'utf8'));
rmSync(out);
for (const l of about.licenses) {
  for (const u of l.used_by) {
    const c = u.crate;
    add(l.id, l.text, { name: c.name, version: c.version, url: c.repository ?? `https://crates.io/crates/${c.name}` });
  }
}

// npm packages the UI ships (not the build tools).
const uiPkg = JSON.parse(read('ui', 'package.json'));
const seen = new Set();
function npm(name) {
  if (seen.has(name) || name === 'pixie') return;
  seen.add(name);
  const dir = join(root, 'ui', 'node_modules', name);
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
  const files = readdirSync(dir).filter((f) => /^(licen[cs]e|copying)/i.test(f));
  if (files.length === 0) throw new Error(`${name}: no licence file found`);
  for (const f of files) {
    add(typeof pkg.license === 'string' ? pkg.license : 'See text', readFileSync(join(dir, f), 'utf8'), {
      name, version: pkg.version, url: pkg.homepage ?? `https://www.npmjs.com/package/${name}`,
    });
  }
  for (const dep of Object.keys(pkg.dependencies ?? {})) npm(dep);
}
Object.keys(uiPkg.dependencies ?? {}).forEach(npm);

// The rest, by hand.
for (const e of JSON.parse(read('docs', 'notices', 'extra.json'))) {
  add(e.license, read('docs', 'notices', e.textFile), { name: e.name, version: e.version ?? '', url: e.url, note: e.note });
}

const list = [...groups.values()];
for (const g of list) g.packages.sort((a, b) => a.name.localeCompare(b.name));
list.sort((a, b) => a.license.localeCompare(b.license) || a.packages[0].name.localeCompare(b.packages[0].name));

mkdirSync(join(root, 'ui', 'src', 'generated'), { recursive: true });
writeFileSync(join(root, 'ui', 'src', 'generated', 'third-party.json'), JSON.stringify({ groups: list }));

const count = new Set(list.flatMap((g) => g.packages.map((p) => `${p.name}@${p.version}`))).size;
let md = `# Third-party notices\n\nPixie is Copyright (c) 2026 JollyGoodSW LLC and Paul Moore, released under the MIT licence (see LICENSE).\n` +
  `It includes the ${count} pieces of software below. Generated by \`just notices\`; do not edit by hand.\n`;
for (const g of list) {
  md += `\n---\n\n## ${g.license}\n\nUsed by: ${g.packages.map((p) => `${p.name}${p.version ? ' ' + p.version : ''}`).join(', ')}\n`;
  for (const p of g.packages) if (p.note) md += `\n- ${p.name}: ${p.note}\n`;
  md += `\n\`\`\`text\n${g.text}\n\`\`\`\n`;
}
writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), md);
console.log(`${count} packages, ${list.length} licence texts`);
